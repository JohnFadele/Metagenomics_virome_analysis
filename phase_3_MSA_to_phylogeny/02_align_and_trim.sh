#!/usr/bin/env bash

# ============================================================
# STEP 2
# REORIENTATION, MULTIPLE SEQUENCE ALIGNMENT,
# HEADER CLEANING AND TRIMMING
#
# Purpose:
#   1. Reorient sequences using MAFFT --adjustdirection
#   2. Perform multiple sequence alignment using MAFFT --auto
#   3. Remove MAFFT "_R_" orientation markers from headers
#   4. Trim poorly aligned/gappy regions using TrimAl
#   5. Validate the final trimmed alignment
#
# INPUT:
#   /home/fadele/ARS_NACA/PPR_phylo/
#       01_sequence_preparation/
#       PPR_WG_phylogeny_seq_clean.fasta
#
# INTERMEDIATE OUTPUTS:
#   PPR_WG_phylogeny_seq_oriented.fasta
#   PPR_WG_phylogeny_seq_aligned.fasta
#   PPR_WG_phylogeny_seq_aligned_clean.fasta
#
# FINAL OUTPUT:
#   PPR_WG_phylogeny_seq_trimmed.fasta
#
# The final *_trimmed.fasta file is the direct input for
# downstream phylogenetic analysis.
# ============================================================

set -Eeuo pipefail


# ============================================================
# USER CONFIGURATION
# ============================================================

PROJECT_DIR="/home/fadele/ARS_NACA/ppr_phylo"

# Output generated by STEP 1
INPUT_FASTA="${PROJECT_DIR}/01_sequence_preparation/ppr_pub_study_og_clean.fasta"

# Step 2 output directory
OUTPUT_DIR="${PROJECT_DIR}/02_alignment"

# Number of CPU threads
THREADS=8


# ============================================================
# OUTPUT FILES
# ============================================================

ORIENTED_FASTA="${OUTPUT_DIR}/ppr_pub_study_og_oriented.fasta"

ALIGNED_FASTA="${OUTPUT_DIR}/ppr_pub_study_og_aligned.fasta"

CLEAN_ALIGNED_FASTA="${OUTPUT_DIR}/ppr_pub_study_og_aligned_clean.fasta"

TRIMMED_FASTA="${OUTPUT_DIR}/ppr_pub_study_og_trimmed.fasta"

TRIMAL_REPORT="${OUTPUT_DIR}/ppr_pub_study_og_trimmed_report.html"

LOG_FILE="${OUTPUT_DIR}/alignment.log"


# ============================================================
# ERROR HANDLER
# ============================================================

error_handler() {

    local EXIT_CODE=$?

    echo
    echo "============================================================"
    echo "ERROR: STEP 2 FAILED"
    echo "============================================================"
    echo
    echo "The failure occurred near line: ${BASH_LINENO[0]}"
    echo "Exit code: ${EXIT_CODE}"
    echo
    echo "All successfully created intermediate files have been"
    echo "retained."
    echo
    echo "Output directory:"
    echo "${OUTPUT_DIR}"
    echo
    echo "Check the log:"
    echo "${LOG_FILE}"
    echo
    echo "============================================================"

    exit "${EXIT_CODE}"
}

trap error_handler ERR


# ============================================================
# CREATE OUTPUT DIRECTORY
# ============================================================

mkdir -p "${OUTPUT_DIR}"


# ============================================================
# CHECK INPUT FILE
# ============================================================

if [[ ! -f "${INPUT_FASTA}" ]]; then

    echo
    echo "ERROR: Step 1 output was not found:"
    echo "${INPUT_FASTA}"
    echo

    exit 1

fi


if [[ ! -s "${INPUT_FASTA}" ]]; then

    echo
    echo "ERROR: Step 1 output exists but is empty:"
    echo "${INPUT_FASTA}"
    echo

    exit 1

fi


# ============================================================
# CHECK REQUIRED SOFTWARE
# ============================================================

for CMD in mafft trimal awk grep sed sort wc; do

    if ! command -v "${CMD}" >/dev/null 2>&1; then

        echo
        echo "ERROR: Required command not found:"
        echo "${CMD}"
        echo

        exit 1

    fi

done


# ============================================================
# INITIALISE LOG
# ============================================================

{
    echo "============================================================"
    echo "STEP 2"
    echo "REORIENTATION + MSA + HEADER CLEANING + TRIMMING"
    echo "============================================================"
    echo
    echo "Start time:        $(date)"
    echo "Project directory: ${PROJECT_DIR}"
    echo "Input FASTA:       ${INPUT_FASTA}"
    echo "Output directory:  ${OUTPUT_DIR}"
    echo "Threads:           ${THREADS}"
    echo
} > "${LOG_FILE}"


# ============================================================
# COUNT INPUT SEQUENCES
# ============================================================

INPUT_COUNT=$(grep -c '^>' "${INPUT_FASTA}" || true)


if [[ "${INPUT_COUNT}" -eq 0 ]]; then

    echo
    echo "ERROR: No FASTA sequences were detected in the input."
    echo

    exit 1

fi


echo "Input sequences: ${INPUT_COUNT}" | tee -a "${LOG_FILE}"


# ============================================================
# STEP 2.1
# MAFFT REORIENTATION
# ============================================================

echo
echo "============================================================"
echo "STEP 2.1 — REORIENTING SEQUENCES"
echo "============================================================"
echo

echo "Running MAFFT --adjustdirection..."
echo
echo "Input:"
echo "${INPUT_FASTA}"
echo
echo "Output:"
echo "${ORIENTED_FASTA}"
echo


if ! mafft \
    --adjustdirection \
    --thread "${THREADS}" \
    "${INPUT_FASTA}" \
    > "${ORIENTED_FASTA}" \
    2>> "${LOG_FILE}"
then

    echo
    echo "ERROR: MAFFT reorientation failed."
    echo

    exit 1

fi


# ------------------------------------------------------------
# Validate oriented FASTA
# ------------------------------------------------------------

if [[ ! -s "${ORIENTED_FASTA}" ]]; then

    echo
    echo "ERROR: MAFFT produced an empty oriented FASTA."
    echo

    exit 1

fi


ORIENTED_COUNT=$(grep -c '^>' "${ORIENTED_FASTA}" || true)


if [[ "${ORIENTED_COUNT}" -ne "${INPUT_COUNT}" ]]; then

    echo
    echo "ERROR: Sequence count changed during reorientation."
    echo
    echo "Input sequences:      ${INPUT_COUNT}"
    echo "Oriented sequences:   ${ORIENTED_COUNT}"
    echo

    exit 1

fi


echo "Reorientation completed successfully." | tee -a "${LOG_FILE}"

echo "Sequences after reorientation: ${ORIENTED_COUNT}" \
    | tee -a "${LOG_FILE}"


# ============================================================
# STEP 2.2
# MULTIPLE SEQUENCE ALIGNMENT
# ============================================================

echo
echo "============================================================"
echo "STEP 2.2 — MULTIPLE SEQUENCE ALIGNMENT"
echo "============================================================"
echo

echo "Running MAFFT --auto..."
echo
echo "Input:"
echo "${ORIENTED_FASTA}"
echo
echo "Output:"
echo "${ALIGNED_FASTA}"
echo


if ! mafft \
    --auto \
    --thread "${THREADS}" \
    "${ORIENTED_FASTA}" \
    > "${ALIGNED_FASTA}" \
    2>> "${LOG_FILE}"
then

    echo
    echo "ERROR: MAFFT multiple sequence alignment failed."
    echo

    exit 1

fi


# ------------------------------------------------------------
# Validate aligned FASTA
# ------------------------------------------------------------

if [[ ! -s "${ALIGNED_FASTA}" ]]; then

    echo
    echo "ERROR: MAFFT produced an empty alignment."
    echo

    exit 1

fi


ALIGNED_COUNT=$(grep -c '^>' "${ALIGNED_FASTA}" || true)


if [[ "${ALIGNED_COUNT}" -ne "${ORIENTED_COUNT}" ]]; then

    echo
    echo "ERROR: Sequence count changed during alignment."
    echo
    echo "Oriented sequences: ${ORIENTED_COUNT}"
    echo "Aligned sequences:  ${ALIGNED_COUNT}"
    echo

    exit 1

fi


echo "Multiple sequence alignment completed successfully." \
    | tee -a "${LOG_FILE}"

echo "Sequences after alignment: ${ALIGNED_COUNT}" \
    | tee -a "${LOG_FILE}"


# ============================================================
# STEP 2.3
# REMOVE MAFFT "_R_" ORIENTATION MARKERS
# ============================================================

echo
echo "============================================================"
echo "STEP 2.3 — CLEANING MAFFT ORIENTATION MARKERS"
echo "============================================================"
echo

echo "Removing '_R_' from FASTA headers."

echo
echo "Input:"
echo "${ALIGNED_FASTA}"

echo
echo "Output:"
echo "${CLEAN_ALIGNED_FASTA}"

echo


awk '
/^>/ {

    # Remove Windows carriage return
    sub(/\r$/, "")

    # Remove MAFFT orientation marker from header only
    gsub(/_R_/, "", $0)

    print

    next
}

{
    # Remove Windows carriage return from sequence lines
    sub(/\r$/, "")

    print
}
' "${ALIGNED_FASTA}" > "${CLEAN_ALIGNED_FASTA}"


# ------------------------------------------------------------
# Validate cleaned alignment
# ------------------------------------------------------------

if [[ ! -s "${CLEAN_ALIGNED_FASTA}" ]]; then

    echo
    echo "ERROR: Cleaned alignment was not created."
    echo

    exit 1

fi


CLEAN_COUNT=$(grep -c '^>' "${CLEAN_ALIGNED_FASTA}" || true)


if [[ "${CLEAN_COUNT}" -ne "${ALIGNED_COUNT}" ]]; then

    echo
    echo "ERROR: Sequence count changed during header cleaning."
    echo
    echo "Aligned sequences: ${ALIGNED_COUNT}"
    echo "Cleaned sequences:  ${CLEAN_COUNT}"
    echo

    exit 1

fi


# Check whether _R_ remains

REMAINING_R_MARKERS=$(
    grep '^>' "${CLEAN_ALIGNED_FASTA}" |
    grep -c '_R_' || true
)


if [[ "${REMAINING_R_MARKERS}" -ne 0 ]]; then

    echo
    echo "ERROR: '_R_' markers remain in ${REMAINING_R_MARKERS} headers."
    echo

    exit 1

fi


echo "MAFFT orientation markers removed successfully." \
    | tee -a "${LOG_FILE}"


# ============================================================
# STEP 2.4
# VALIDATE ALIGNMENT BEFORE TRIMMING
# ============================================================

echo
echo "============================================================"
echo "STEP 2.4 — VALIDATING ALIGNMENT"
echo "============================================================"
echo


# ------------------------------------------------------------
# Calculate sequence lengths.
#
# Every sequence in a multiple sequence alignment must have
# the same length.
# ------------------------------------------------------------

ALIGNMENT_LENGTHS=$(
    awk '
    /^>/ {

        if (seq != "")
            print length(seq)

        seq = ""

        next
    }

    {
        gsub(/[ \t\r\n]/, "", $0)
        seq = seq $0
    }

    END {

        if (seq != "")
            print length(seq)

    }
    ' "${CLEAN_ALIGNED_FASTA}" |
    sort -nu
)


NUMBER_OF_LENGTHS=$(echo "${ALIGNMENT_LENGTHS}" | wc -l)


if [[ "${NUMBER_OF_LENGTHS}" -ne 1 ]]; then

    echo
    echo "ERROR: The alignment contains sequences of different lengths."
    echo
    echo "Detected lengths:"
    echo "${ALIGNMENT_LENGTHS}"
    echo

    exit 1

fi


ALIGNMENT_LENGTH=$(echo "${ALIGNMENT_LENGTHS}" | head -n 1)


if [[ "${ALIGNMENT_LENGTH}" -eq 0 ]]; then

    echo
    echo "ERROR: Alignment length is zero."
    echo

    exit 1

fi


echo "Sequences:       ${CLEAN_COUNT}" \
    | tee -a "${LOG_FILE}"

echo "Alignment length: ${ALIGNMENT_LENGTH} nt" \
    | tee -a "${LOG_FILE}"


# ============================================================
# STEP 2.5
# TRIM ALIGNMENT WITH TRIMAL
# ============================================================

echo
echo "============================================================"
echo "STEP 2.5 — TRIMMING ALIGNMENT WITH TRIMAL"
echo "============================================================"
echo

echo "Running:"
echo "trimal -automated1"
echo

echo "Input:"
echo "${CLEAN_ALIGNED_FASTA}"

echo
echo "Output:"
echo "${TRIMMED_FASTA}"

echo


if ! trimal \
    -in "${CLEAN_ALIGNED_FASTA}" \
    -automated1 \
    -out "${TRIMMED_FASTA}" \
    -htmlout "${TRIMAL_REPORT}" \
    >> "${LOG_FILE}" \
    2>&1
then

    echo
    echo "ERROR: TrimAl failed."
    echo
    echo "The intermediate alignment files have been retained."
    echo

    exit 1

fi


# ============================================================
# VALIDATE FINAL TRIMMED ALIGNMENT
# ============================================================

echo
echo "============================================================"
echo "VALIDATING FINAL TRIMMED ALIGNMENT"
echo "============================================================"
echo


if [[ ! -s "${TRIMMED_FASTA}" ]]; then

    echo
    echo "ERROR: TrimAl did not produce a final FASTA."
    echo

    exit 1

fi


FINAL_COUNT=$(grep -c '^>' "${TRIMMED_FASTA}" || true)


if [[ "${FINAL_COUNT}" -eq 0 ]]; then

    echo
    echo "ERROR: Final trimmed FASTA contains no sequences."
    echo

    exit 1

fi


# ------------------------------------------------------------
# Check final alignment length
# ------------------------------------------------------------

FINAL_LENGTHS=$(
    awk '
    /^>/ {

        if (seq != "")
            print length(seq)

        seq = ""

        next
    }

    {
        gsub(/[ \t\r\n]/, "", $0)
        seq = seq $0
    }

    END {

        if (seq != "")
            print length(seq)

    }
    ' "${TRIMMED_FASTA}" |
    sort -nu
)


FINAL_NUMBER_OF_LENGTHS=$(echo "${FINAL_LENGTHS}" | wc -l)


if [[ "${FINAL_NUMBER_OF_LENGTHS}" -ne 1 ]]; then

    echo
    echo "ERROR: Final trimmed FASTA is not a uniform alignment."
    echo
    echo "Detected lengths:"
    echo "${FINAL_LENGTHS}"
    echo

    exit 1

fi


FINAL_ALIGNMENT_LENGTH=$(echo "${FINAL_LENGTHS}" | head -n 1)


# ------------------------------------------------------------
# Confirm sequence count was retained
# ------------------------------------------------------------

if [[ "${FINAL_COUNT}" -ne "${CLEAN_COUNT}" ]]; then

    echo
    echo "WARNING: TrimAl changed the number of sequences."
    echo
    echo "Before trimming: ${CLEAN_COUNT}"
    echo "After trimming:  ${FINAL_COUNT}"
    echo

fi


# ============================================================
# FINAL SUMMARY
# ============================================================

{
    echo
    echo "============================================================"
    echo "STEP 2 FINAL SUMMARY"
    echo "============================================================"
    echo
    echo "Input sequences:                 ${INPUT_COUNT}"
    echo "After reorientation:             ${ORIENTED_COUNT}"
    echo "After MSA:                       ${ALIGNED_COUNT}"
    echo "After header cleaning:           ${CLEAN_COUNT}"
    echo "After trimming:                  ${FINAL_COUNT}"
    echo
    echo "Alignment length before trim:    ${ALIGNMENT_LENGTH} nt"
    echo "Alignment length after trim:     ${FINAL_ALIGNMENT_LENGTH} nt"
    echo
    echo "Final phylogenetic input:"
    echo "${TRIMMED_FASTA}"
    echo
    echo "TrimAl report:"
    echo "${TRIMAL_REPORT}"
    echo
    echo "End time: $(date)"
    echo
    echo "STEP 2 COMPLETED SUCCESSFULLY"
    echo "============================================================"

} >> "${LOG_FILE}"


# ============================================================
# FINAL MESSAGE
# ============================================================

echo
echo "============================================================"
echo "STEP 2 COMPLETED SUCCESSFULLY"
echo "============================================================"
echo
echo "Intermediate files retained in:"
echo "${OUTPUT_DIR}"
echo
echo "Final trimmed alignment:"
echo "${TRIMMED_FASTA}"
echo
echo "Sequences: ${FINAL_COUNT}"
echo "Alignment length: ${FINAL_ALIGNMENT_LENGTH} nt"
echo
echo "TrimAl report:"
echo "${TRIMAL_REPORT}"
echo
echo "Log:"
echo "${LOG_FILE}"
echo
echo "This *_trimmed.fasta file is the input for"
echo "the downstream phylogenetic analysis."
echo "============================================================"